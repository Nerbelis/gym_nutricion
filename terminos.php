    <h2>Términos, Condiciones y Marco Científico</h2>
    <p style="text-align: center; font-size: 13px; color: #64748b;">NercoFit — Sistema Automatizado de Referencia Antropométrica</p>

    <h3>1. Descargo de Responsabilidad Informativa</h3>
    <p>Toda la información, diagnósticos estimativos (incluyendo el cálculo del índice de masa corporal, estado eutrófico, porcentaje de grasa corporal y gasto calórico diario), así como las pautas de fuerza y recomendaciones generadas por <strong>NercoFit</strong>, tienen un <strong>carácter estrictamente informativo, educativo y de orientación en bienestar</strong>.</p>
    <p>Este software automatizado <strong>no constituye un diagnóstico médico, clínico ni nutricional formal</strong>, y de ninguna manera sustituye la consulta, evaluación o supervisión de un médico especialista o profesional de la salud calificado.</p>

    <h3>2. Basamento Metodológico y Científico (OMS y Organismos)</h3>
    <p>Los algoritmos y fórmulas de referencia implementados en este sistema se basan en estándares internacionales de salud pública:</p>
    <ul>
        <li><strong>Clasificación Eutrófica e IMC:</strong> Basado estrictamente en los parámetros e intervalos de referencia establecidos por la <strong>Organización Mundial de la Salud (OMS)</strong> para la evaluación nutricional en adultos.</li>
        <li><strong>Composición Corporal (Grasa):</strong> Estimaciones calculadas mediante las <strong>Ecuaciones de Deurenberg</strong>, validadas científicamente para estimar el porcentaje de grasa corporal en función de la edad, el sexo y el IMC.</li>
        <li><strong>Gasto Energético:</strong> Calculado mediante la fórmula matemática de <strong>Harris-Benedict (revisada)</strong> para determinar la Tasa Metabólica Basal (TMB) y el Gasto Energético Total Diario (TDEE).</li>
    </ul>

    <h3>3. Privacidad y Protección de Datos</h3>
    <p>Los datos antropométricos y de transacciones introducidos son tratados con estricta confidencialidad y se procesan exclusivamente para generar el reporte de consulta y las pautas sugeridas.</p>

